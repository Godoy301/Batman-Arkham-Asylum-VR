"""Generate mechanical COM forwarding from the installed Microsoft SDK.
Only forwarding is generated; compatibility policy lives in managed9.cpp.
"""
import re
from pathlib import Path
sdk=Path('C:/Program Files (x86)/Windows Kits/10/Include/10.0.26100.0/shared/d3d9.h').read_text()
names=['Device','Texture','CubeTexture','VolumeTexture','VertexBuffer','IndexBuffer','Surface','Volume','StateBlock']
out=['// Generated by tools/generate_device9_forward.py from Windows SDK 10.0.26100.0.','// Mechanical interface declarations; policy is in managed9.cpp.','#pragma once','#include <d3d9.h>','#include <wrl/client.h>','namespace bvr::aa::managed9 {','using Microsoft::WRL::ComPtr;']
for name in names:
    interface='IDirect3D'+name+'9'
    body=sdk.split('DECLARE_INTERFACE_('+interface+',',1)[1].split('};',1)[0]
    methods=re.findall(r'STDMETHOD(?:_\(([^,]+),\s*(\w+)\)|\((\w+)\))\s*\((.*?)\)\s*PURE',body,re.S)
    out+=['class '+name+'Forward : public '+interface+' {','public:',' ComPtr<'+interface+'> real;']
    for ret,n1,n2,parameters in methods:
        n=n1 or n2; ret=ret or 'HRESULT'
        p=re.sub(r'\s+',' ',parameters).replace('THIS_','').replace('THIS','').strip()
        parts=[v.strip() for v in p.split(',')] if p else []
        args=[]
        for i,v in enumerate(parts):
            # Three Device9 matrix/light declarations omit their parameter name.
            if re.search(r'\*\s*$',v) or len(v.split())==1: v+=' arg'+str(i)
            parts[i]=v; args.append(re.search(r'(\w+)(?:\[[^]]*\])?$',v).group(1))
        out+=[' '+ret+' WINAPI '+n+'('+', '.join(parts)+') override { '+('' if ret=='void' else 'return ')+'real->'+n+'('+', '.join(args)+'); }']
    out+=['};']
out+=['}']
Path('batman_asylum/src/game/asylum/device9_forward.h').write_text('\n'.join(out)+'\n')
