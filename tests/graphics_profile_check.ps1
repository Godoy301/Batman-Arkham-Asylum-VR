$ErrorActionPreference='Stop'
. (Join-Path $PSScriptRoot '../tools/Graphics-Profile.ps1')
$dir=Join-Path ([IO.Path]::GetTempPath()) ('asylum-profile-'+[Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $dir | Out-Null
foreach($encoding in @([Text.Encoding]::GetEncoding(28591),[Text.Encoding]::Unicode)) {
 $path=Join-Path $dir 'engine.ini';$backup=Join-Path $dir 'engine.backup'
 $text="[Engine.GameEngine]`r`nbSmoothFrameRate=TRUE`r`nMaxSmoothedFrameRate=62`r`n[SystemSettings]`r`nResX=1680`r`nResY=1050`r`nFullscreen=True`r`nUseVsync=True`r`nMotionBlur=True`r`nDepthOfField=True`r`nUnrelated=keep`r`n[SystemSettingsEditor]`r`nResX=960`r`nResY=720`r`n"
 $bytes=$encoding.GetPreamble()+$encoding.GetBytes($text)
 [IO.File]::WriteAllBytes($path,$bytes);[IO.File]::WriteAllBytes($backup,$bytes)
 $hash=(Get-FileHash -LiteralPath $path).Hash
 Set-AsylumVRProfile $path 2284 2448
 $out=$encoding.GetString([IO.File]::ReadAllBytes($path))
 foreach($expected in @('ResX=2284','ResY=2448','MotionBlur=False','DepthOfField=False','MaxMultisamples=1','bSmoothFrameRate=False','MaxSmoothedFrameRate=300','Unrelated=keep',"[SystemSettingsEditor]`r`nResX=960`r`nResY=720")) {
  if(!$out.Contains($expected)) {throw "Profile corruption: $expected"}
 }
 Restore-AsylumProfile @{files=@(@{path=$path;backup=$backup;sha256=$hash})}
 if((Get-FileHash -LiteralPath $path).Hash -ne $hash) {throw 'Byte-exact restoration failed.'}
}
# Real file pipeline: configure the base and generated files, then rebuild the
# generated file FROM the base as UE3 startup can do. The cap must remain off.
$fakeGame=Join-Path $dir 'game';$fakeConfig=Join-Path $fakeGame 'BmGame/Config'
New-Item -ItemType Directory -Path $fakeConfig -Force | Out-Null
$base=Join-Path $fakeConfig 'DefaultEngine.ini';$generated=Join-Path $fakeConfig 'BmEngine.ini'
$paths=@(Get-AsylumConfigPaths $fakeGame)
if($paths[0] -ne $base -or $paths[1] -ne $generated) {throw 'Base config omitted from the journal path list.'}
$records=@();$encoding=[Text.Encoding]::GetEncoding(28591)
foreach($file in @($base,$generated)) {
 [IO.File]::WriteAllBytes($file,$encoding.GetBytes($text));$saved="$file.backup"
 Copy-Item -LiteralPath $file -Destination $saved
 $records+=@{path=$file;backup=$saved;sha256=(Get-FileHash -LiteralPath $file).Hash}
 Set-AsylumVRProfile $file 2284 2448
}
Copy-Item -LiteralPath $base -Destination $generated -Force
$status=@(Get-AsylumProfileStatus @($base,$generated))
foreach($record in $status) {
 if($record.values.bSmoothFrameRate[0] -ne 'False' -or $record.values.MaxSmoothedFrameRate[0] -ne '300' -or $record.values.ResX[0] -ne '2284' -or $record.values.UseVsync[0] -ne 'False') {throw 'Startup regeneration restored the stock cap or graphics profile.'}
}
Restore-AsylumProfile @{files=$records}
foreach($record in $records) {if((Get-FileHash -LiteralPath $record.path).Hash -ne $record.sha256) {throw 'Base/generated byte-exact rollback failed.'}}
foreach($record in $records) {Remove-Item -LiteralPath $record.path,$record.backup}
Remove-Item -LiteralPath $fakeConfig,(Join-Path $fakeGame 'BmGame'),$fakeGame
Remove-Item -LiteralPath (Join-Path $dir 'engine.ini'),(Join-Path $dir 'engine.backup')
Remove-Item -LiteralPath $dir
Write-Output 'PASS: ANSI/UTF-16 profiles, base/default config journal inclusion, cap disabled after generated-file rebuild from base, observed profile values, editor section preserved, byte-exact base/generated rollback.'
